def sync_shadowing_seed_videos():
    """
    Idempotently seeds public JLPT shadowing videos into the database.
    Does not delete or alter any user-created videos (created_by is not None).
    """
    seed_data = get_seed_videos_data()
    synced_count = 0

    with transaction.atomic():
        for item in seed_data:
            youtube_id = item["youtube_id"]
            video, created = ShadowingVideo.objects.update_or_create(
                youtube_id=youtube_id,
                created_by=None,
                defaults={
                    "youtube_url": item["youtube_url"],
                    "title": item["title"],
                    "description": item["description"],
                    "topic": item["topic"],
                    "level": item["level"],
                    "media_source": item["media_source"],
                    "thumbnail_url": item["thumbnail_url"],
                    "duration_seconds": item["duration_seconds"],
                    "segments": item["segments"],
                    "exercises": item["exercises"],
                    "is_public": True,
                },
            )
            synced_count += 1

    return synced_count
