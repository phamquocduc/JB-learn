def get_kanji_n3_records(deduplicate: bool = False) -> list[dict]:
    """
    Returns structured Kanji N3 records from all 9 pages (227 rows).
    When deduplicate=True, merges duplicate Kanji entries across the 9 pages while preserving order.
    """
    seen: dict[str, dict] = {}
    records: list[dict] = []

    for lesson, kanji, reading, han_viet, meaning, source in KANJI_N3_RAW_RECORDS:
        hv_upper = han_viet.strip().upper()
        if deduplicate and kanji in seen:
            existing = seen[kanji]
            if meaning.lower() not in existing["meaning"].lower():
                existing["meaning"] = f"{existing['meaning']}; {meaning}"
            continue

        item = {
            "lesson": lesson,
            "kanji": kanji.strip(),
            "reading": reading.strip(),
            "han_viet": hv_upper,
            "meaning": meaning.strip(),
            "source": source,
        }
        seen[kanji] = item
        records.append(item)

    return records
